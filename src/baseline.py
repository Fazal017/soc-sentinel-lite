"""Peer-group behavioural baselining (v2).

A fixed threshold ("5 failures in 5 minutes") cannot tell a sysadmin
who mistypes from an attacker who guesses — both cross it. Sentinel v2
instead learns, per user, what *normal* looks like from a 7-day
history, and compares each new event against *that user's own* peer
group:

* ``login_hours`` — the hours of day the user normally logs in
  (mean hour and spread, plus the observed hour set).
* ``normal_hosts`` / ``normal_ips`` — the hosts / IPs the user has
  ever used in the history window.
* ``failure_rate`` — failed / (failed + successful) logins for the
  user, compared with the *peer-group median* (median, not mean, so
  one attacked account cannot drag the baseline with it).
* ``distinct_ips_per_day`` — how many source IPs the user normally
  appears from in a day.

Deviation is scored 0–1 per event as a rarity score, with a reason
list an analyst can read — never a black box.  A login at 10:00 from
the user's usual IP and host scores ~0.1.  The same login at 02:00
from an IP and host the user has never used scores ~0.9.

The baseline is learned from ``logs/history_7d.log`` (generated by
``scripts/generate_history.py``).  If no history is supplied, the
baseline is empty and every unseen entity is treated as moderately
rare (0.5) rather than crashing — v2 degrades gracefully.
"""

from __future__ import annotations

import math
from collections import Counter, defaultdict
from datetime import datetime


def _median(values: list[float]) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    n = len(s)
    return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2.0


def _mad(values: list[float], med: float) -> float:
    if not values:
        return 0.0
    return _median([abs(v - med) for v in values]) or 1.0


class Baseline:
    """Learned per-user + peer-group behaviour from history events."""

    def __init__(self, history_events: list[dict] | None = None):
        self.users: dict[str, dict] = {}
        self.peer_failure_median: float = 0.0
        self.peer_failure_mad: float = 1.0
        self.peer_ips_median: float = 1.0
        self.total_events: int = 0
        if history_events:
            self.learn(history_events)

    def learn(self, events: list[dict]) -> None:
        self.total_events = len(events)
        per_user: dict[str, dict] = defaultdict(lambda: {
            "hours": [], "hour_set": set(), "hosts": set(), "ips": set(),
            "failed": 0, "success": 0, "ips_per_day": defaultdict(set),
            "sudo_success": 0, "sudo_failure": 0,
        })
        for e in events:
            user = e.get("user")
            if not user:
                continue
            u = per_user[user]
            ts = e.get("timestamp")
            if ts:
                u["hours"].append(ts.hour)
                u["hour_set"].add(ts.hour)
                u["ips_per_day"][ts.date()].add(e.get("src_ip"))
            if e.get("host"):
                u["hosts"].add(e["host"])
            if e.get("src_ip"):
                u["ips"].add(e["src_ip"])
            if e["event_type"] == "failed_login":
                u["failed"] += 1
            elif e["event_type"] == "successful_login":
                u["success"] += 1
            elif e["event_type"] == "sudo_success":
                u["sudo_success"] += 1
            elif e["event_type"] == "sudo_failure":
                u["sudo_failure"] += 1
        failure_rates, ips_counts = [], []
        for user, u in per_user.items():
            total = u["failed"] + u["success"]
            fr = u["failed"] / total if total else 0.0
            mean_hour = sum(u["hours"]) / len(u["hours"]) if u["hours"] else 12.0
            var = sum((h - mean_hour) ** 2 for h in u["hours"]) / len(u["hours"]) if u["hours"] else 1.0
            self.users[user] = {
                "mean_hour": mean_hour,
                "hour_std": math.sqrt(var) or 1.0,
                "hour_set": sorted(u["hour_set"]),
                "hosts": sorted(u["hosts"]),
                "ips": sorted(u["ips"]),
                "failure_rate": fr,
                "failed": u["failed"], "success": u["success"],
                "distinct_ips_per_day_median": _median(
                    [len(v) for v in u["ips_per_day"].values()]) if u["ips_per_day"] else 1.0,
                "sudo_success": u["sudo_success"],
                "sudo_failure": u["sudo_failure"],
            }
            failure_rates.append(fr)
            ips_counts.append(self.users[user]["distinct_ips_per_day_median"])
        self.peer_failure_median = _median(failure_rates)
        self.peer_failure_mad = _mad(failure_rates, self.peer_failure_median)
        self.peer_ips_median = _median(ips_counts)

    # -- scoring ------------------------------------------------------
    def score_event(self, event: dict) -> tuple[float, list[str]]:
        """Return (rarity 0-1, reasons) for one event vs. the baseline."""
        reasons: list[str] = []
        score = 0.0
        user = event.get("user")
        ts = event.get("timestamp")
        if not user or user not in self.users:
            # Unknown user: moderately rare, never a certainty.
            score += 0.35
            reasons.append(f"unknown user '{user}' — no 7-day baseline")
            # Still check host/IP novelty against the global picture.
            return min(score, 1.0), reasons
        u = self.users[user]
        if ts:
            hour = ts.hour
            if hour not in u["hour_set"]:
                score += 0.35
                reasons.append(f"login at {hour:02d}:00 — outside normal hours "
                               f"{u['hour_set']}")
                if hour < 5 or hour > 22:
                    score += 0.20
                    reasons.append("off-hours (before 05:00 / after 22:00)")
            else:
                # z-score on hour distance from the user's mean hour.
                z = abs(hour - u["mean_hour"]) / max(u["hour_std"], 1.0)
                if z > 2.0:
                    score += 0.15
                    reasons.append(f"hour z-score {z:.1f} vs. user mean {u['mean_hour']:.1f}")
        host = event.get("host")
        if host and host not in u["hosts"]:
            score += 0.35
            reasons.append(f"host '{host}' never used by '{user}' in 7 days")
        ip = event.get("src_ip")
        if ip and ip not in u["ips"]:
            score += 0.35
            reasons.append(f"source IP {ip} never used by '{user}' in 7 days")
        if event.get("event_type") == "failed_login":
            # Peer-group failure-rate check: how far is this user from
            # the peer median, in MAD units?
            z = (u["failure_rate"] - self.peer_failure_median) / max(self.peer_failure_mad, 0.01)
            if z > 2.0:
                score += 0.15
                reasons.append(f"user failure rate {u['failure_rate']:.2f} vs. "
                               f"peer median {self.peer_failure_median:.2f} (z={z:.1f})")
        if not reasons:
            reasons.append("matches baseline: normal hour, host and IP for this user")
        return min(score, 1.0), reasons

    def is_anomalous(self, event: dict, threshold: float = 0.6) -> bool:
        score, _ = self.score_event(event)
        return score >= threshold

    def summary(self) -> dict:
        return {
            "total_history_events": self.total_events,
            "users": sorted(self.users),
            "peer_failure_rate_median": round(self.peer_failure_median, 3),
            "peer_distinct_ips_per_day_median": self.peer_ips_median,
            "per_user": {
                user: {
                    "mean_hour": round(v["mean_hour"], 1),
                    "hours": v["hour_set"],
                    "hosts": v["hosts"], "ips": v["ips"],
                    "failure_rate": round(v["failure_rate"], 3),
                    "logins": v["success"],
                } for user, v in sorted(self.users.items())
            },
        }


def learn_baseline(history_events: list[dict]) -> Baseline:
    return Baseline(history_events)
